#!/usr/bin/env python3
"""Embed pinned Mozilla CA roots in the portable FFmpeg Mbed TLS backend.

This prepares source only; it does not configure, compile or execute FFmpeg.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import urllib.request


HERE = Path(__file__).resolve().parent


def checked_bytes(path: Path, expected: str) -> bytes:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError(f"SHA256 mismatch: {path.name}")
    return data


def render_header(pem: bytes, manifest: dict) -> bytes:
    # Adjacent C strings preserve every PEM byte and add exactly one trailing
    # NUL, which mbedtls_x509_crt_parse requires for PEM input.
    lines = [
        "/* Generated by scripts/ffmpeg-tls/prepare.py; do not edit.",
        f" * Mozilla CA bundle {manifest['ca_version']}; MPL-2.0.",
        f" * Source: {manifest['ca_url']}",
        f" * SHA256: {manifest['ca_sha256']}",
        " * Original PEM and license are provided with the decoder sources.",
        " */",
        "#ifndef VK_FAST_MOZILLA_CA_H",
        "#define VK_FAST_MOZILLA_CA_H",
        "static const unsigned char vk_fast_mozilla_ca[] =",
    ]
    # Keep UTF-8 certificate-name comments byte-for-byte too. Fixed-width
    # octal escapes avoid C's variable-width hex escapes consuming later bytes.
    def literal(line: bytes) -> str:
        escapes = {10: r"\n", 13: r"\r", 34: r'\"', 63: r"\?", 92: r"\\"}
        return '"' + "".join(
            escapes.get(value, chr(value) if 32 <= value <= 126 else f"\\{value:03o}")
            for value in line
        ) + '"'

    lines.extend(literal(line) for line in pem.splitlines(True))
    lines.extend([";", "#endif", ""])
    return "\n".join(lines).encode("ascii")


def prepare(source: Path, download_dir: Path) -> dict:
    manifest = json.loads((HERE / "trust-source.json").read_text())
    name = f"cacert-{manifest['ca_version']}.pem"
    local = HERE / name
    cached = download_dir / name
    if local.exists():
        pem = checked_bytes(local, manifest["ca_sha256"])
    elif cached.exists():
        pem = checked_bytes(cached, manifest["ca_sha256"])
    else:
        # Use the immutable dated URL, never the mutable latest bundle. The
        # checked-in hash was verified against curl's published SHA256 file.
        with urllib.request.urlopen(manifest["ca_url"], timeout=60) as response:
            pem = response.read(manifest["ca_bytes"] + 1)
        if hashlib.sha256(pem).hexdigest() != manifest["ca_sha256"]:
            raise ValueError("SHA256 mismatch: downloaded Mozilla CA bundle")
    if len(pem) != manifest["ca_bytes"] or pem.count(b"-----BEGIN CERTIFICATE-----") != manifest["ca_certificates"]:
        raise ValueError("Unexpected Mozilla CA bundle size or certificate count")

    target = source / "libavformat/tls_mbedtls.c"
    pristine = manifest["ffmpeg_tls_mbedtls_pristine_sha256"]
    patched = manifest["ffmpeg_tls_mbedtls_patched_sha256"]
    target_hash = hashlib.sha256(target.read_bytes()).hexdigest()
    if target_hash not in (pristine, patched):
        raise ValueError("tls_mbedtls.c is not the pinned pristine or patched FFmpeg 9.0.2 source")
    patch = HERE / "ffmpeg-9.0.2-embedded-mozilla-ca.patch"
    checked_bytes(patch, manifest["patch_sha256"])

    download_dir.mkdir(parents=True, exist_ok=True)
    if cached.exists():
        checked_bytes(cached, manifest["ca_sha256"])
    else:
        cached.write_bytes(pem)
    header = source / "libavformat/vk_fast_mozilla_ca.h"
    rendered = render_header(pem, manifest)
    if not header.exists() or header.read_bytes() != rendered:
        header.write_bytes(rendered)
    if target_hash == pristine:
        subprocess.run(
            ["patch", "--batch", "--forward", "--silent", "-p1", "-i", str(patch)],
            cwd=source,
            check=True,
        )
    checked_bytes(target, patched)
    return {
        "ca_version": manifest["ca_version"],
        "ca_sha256": manifest["ca_sha256"],
        "ca_certificates": manifest["ca_certificates"],
        "header_sha256": hashlib.sha256(rendered).hexdigest(),
        "tls_mbedtls_sha256": patched,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--download-dir", type=Path, required=True)
    args = parser.parse_args()
    try:
        result = prepare(args.source.resolve(), args.download_dir.resolve())
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"FFmpeg CA preparation failed: {error}", file=sys.stderr)
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
